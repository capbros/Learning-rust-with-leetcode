pub struct Solution;

impl Solution {
    pub fn max_ice_cream(costs: Vec<i32>, mut coins: i32) -> i32 {
        let mut cost_map = vec![0; 100_000];
        for cost in costs {
            cost_map[(cost - 1) as usize] += 1;
        }

        let mut res = 0;
        let mut cost = 1;
        while cost <= cost_map.len() && coins >= cost as i32 {
            let amount = &mut cost_map[cost - 1];
            while *amount > 0 && coins >= (cost as i32) {
                coins -= cost as i32;
                res += 1;
                *amount -= 1;
            }
            cost += 1;
        }
        res
    }
}

